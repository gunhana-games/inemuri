function pick(a) { return a[Math.floor(Math.random() * a.length)]; }
function randInt(a, b) { return a + Math.floor(Math.random() * (b - a + 1)); }

// ----- 問題を書くための道具 -----
// ask(問題, 正解, まちがい1, まちがい2)
function ask(q, a, w1, w2) { return { q, a, w: [w1, w2], c: (t) => `「${q.replace(/？$/, '')}」に「${t}」と答えた` }; }
// yomi(漢字, 正しい読み, まちがい1, まちがい2)
function yomi(word, a, w1, w2) { return { q: `「${word}」の読みは？`, a, w: [w1, w2], c: (t) => `「${word}」を「${t}」と読んだ` }; }
// kaku(読み, 正しい漢字, まちがい1, まちがい2)
function kaku(r, a, w1, w2) { return { q: `「${r}」を漢字で書くと？`, a, w: [w1, w2], c: (t) => `「${r}」を「${t}」と書いた` }; }
// imi(言葉, 正しい意味, まちがい1, まちがい2)
function imi(word, a, w1, w2) { return { q: `「${word}」の意味は？`, a, w: [w1, w2], c: (t) => `「${word}」を「${t}」という意味だと思った` }; }
